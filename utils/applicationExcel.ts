import * as XLSX from 'xlsx';
import { Application, InstallmentCompany, FinancingProgram, STATUS_ARABIC, ApplicationStatus } from '../types';

/**
 * Exports existing applications/cases into a full Excel (.xlsx) file.
 * Preserves the Application ID column so users can edit the file and re-upload it to update existing cases!
 */
export function exportApplicationsToExcel(
  applications: Application[],
  filenamePrefix: string = 'حالات_التقسيط_منظومة_كروبسا'
) {
  const dataRows = applications.map(app => {
    return {
      'رقم الطلب (ID)': app.id,
      'اسم العميل': app.clientName || '',
      'الرقم القومي': app.clientNationalId || '',
      'رقم الهاتف': app.phoneNumber || app.clientPhone || '',
      'رقم الواتساب': app.whatsappNumber || app.phoneNumber || '',
      'المحافظة': app.governorate || 'القاهرة',
      'المهنة / النشاط': app.profession || '',
      'المبلغ المطلوب (جنيه)': Number(app.requestedAmount) || 0,
      'المبلغ المعتمد (جنيه)': Number(app.approvedAmount) || 0,
      'مدة التقسيط (شهور)': Number(app.durationMonths) || 12,
      'شركة التمويل': app.companyName || '',
      'البرنامج التمويلي': app.selectedProgramName || '',
      'حالة الطلب': STATUS_ARABIC[app.status] || app.status,
      'تاريخ التقديم': app.submittedAt ? app.submittedAt.split('T')[0] : '',
      'تاريخ آخر مرحلة': app.lastStageDate ? app.lastStageDate.split('T')[0] : (app.submittedAt ? app.submittedAt.split('T')[0] : ''),
      'اسم المندوب': app.salesmanName || '',
      'سبب الرفض (إن وجد)': app.rejectionReason || '',
      'ملاحظات وتفاصيل': app.description || app.rejectionNotes || app.reviewNote || ''
    };
  });

  const ws = XLSX.utils.json_to_sheet(dataRows);

  // Set nice column widths for RTL display
  ws['!cols'] = [
    { wch: 24 }, // رقم الطلب
    { wch: 28 }, // اسم العميل
    { wch: 18 }, // الرقم القومي
    { wch: 16 }, // رقم الهاتف
    { wch: 16 }, // رقم الواتساب
    { wch: 14 }, // المحافظة
    { wch: 20 }, // المهنة
    { wch: 22 }, // المبلغ المطلوب
    { wch: 22 }, // المبلغ المعتمد
    { wch: 18 }, // مدة التقسيط
    { wch: 26 }, // شركة التمويل
    { wch: 24 }, // البرنامج التمويلي
    { wch: 22 }, // حالة الطلب
    { wch: 16 }, // تاريخ التقديم
    { wch: 16 }, // تاريخ آخر مرحلة
    { wch: 20 }, // اسم المندوب
    { wch: 26 }, // سبب الرفض
    { wch: 35 }  // ملاحظات
  ];

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'طلبات_التقسيط');

  const today = new Date().toISOString().split('T')[0];
  XLSX.writeFile(wb, `${filenamePrefix}_${today}.xlsx`);
}

